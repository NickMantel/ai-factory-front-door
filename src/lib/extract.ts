import "server-only";
import JSZip from "jszip";
import mammoth from "mammoth";
import { extractText } from "unpdf";
import { describeImage } from "./claude";

// Upper bound per document, well inside the model's context window.
const MAX_CHARS = 400_000;

function decodeXml(s: string) {
  return s
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&");
}

function htmlToText(html: string) {
  return decodeXml(
    html
      .replace(/<(script|style)[\s\S]*?<\/\1>/gi, "")
      .replace(/<(br|\/p|\/div|\/li|\/h\d|\/tr)>/gi, "\n")
      .replace(/<[^>]+>/g, " ")
      .replace(/&nbsp;/g, " "),
  )
    .replace(/[ \t]+/g, " ")
    .replace(/\n\s*\n\s*\n+/g, "\n\n")
    .trim();
}

async function pptxToText(buf: Buffer) {
  const zip = await JSZip.loadAsync(buf);
  const slideNum = (p: string) => Number(p.match(/(\d+)\.xml$/)?.[1] ?? 0);
  const slides = Object.keys(zip.files)
    .filter((p) => /^ppt\/slides\/slide\d+\.xml$/.test(p))
    .sort((a, b) => slideNum(a) - slideNum(b));
  const out: string[] = [];
  for (const p of slides) {
    const xml = await zip.files[p].async("string");
    const paras = xml
      .split(/<\/a:p>/)
      .map((para) => [...para.matchAll(/<a:t>([\s\S]*?)<\/a:t>/g)].map((m) => decodeXml(m[1])).join(""))
      .filter((t) => t.trim());
    const notesPath = `ppt/notesSlides/notesSlide${slideNum(p)}.xml`;
    let notes = "";
    if (zip.files[notesPath]) {
      const nx = await zip.files[notesPath].async("string");
      notes = [...nx.matchAll(/<a:t>([\s\S]*?)<\/a:t>/g)].map((m) => decodeXml(m[1])).join(" ").trim();
    }
    out.push(`--- Slide ${slideNum(p)} ---\n${paras.join("\n")}${notes ? `\n[Speaker notes] ${notes}` : ""}`);
  }
  return out.join("\n\n");
}

async function xlsxToText(buf: Buffer) {
  const zip = await JSZip.loadAsync(buf);
  const shared = zip.files["xl/sharedStrings.xml"];
  if (!shared) return "";
  const xml = await shared.async("string");
  return [...xml.matchAll(/<t[^>]*>([\s\S]*?)<\/t>/g)].map((m) => decodeXml(m[1])).join(" | ");
}

export async function extractDocument(file: File): Promise<{ text: string; truncated: boolean }> {
  const name = file.name.toLowerCase();
  const buf = Buffer.from(await file.arrayBuffer());
  let text: string;

  if (name.endsWith(".pdf") || file.type === "application/pdf") {
    const { text: t } = await extractText(new Uint8Array(buf), { mergePages: true });
    text = t;
  } else if (name.endsWith(".docx")) {
    text = (await mammoth.extractRawText({ buffer: buf })).value;
  } else if (name.endsWith(".pptx")) {
    text = await pptxToText(buf);
  } else if (name.endsWith(".xlsx")) {
    text = await xlsxToText(buf);
  } else if (/\.(html?|xml)$/.test(name) || file.type === "text/html") {
    text = htmlToText(buf.toString("utf8"));
  } else if (/^image\/(png|jpe?g|gif|webp)$/.test(file.type)) {
    text = `[Image description generated by Claude]\n${await describeImage(buf.toString("base64"), file.type, file.name)}`;
  } else if (file.type.startsWith("text/") || /\.(md|txt|csv|json|ya?ml)$/.test(name)) {
    text = buf.toString("utf8");
  } else {
    throw new Error(`Unsupported file type: ${file.name}. Try PDF, Word, PowerPoint, Excel, HTML, Markdown, text or an image.`);
  }

  text = text.trim();
  if (!text) throw new Error(`No readable text found in ${file.name}. If it's a scanned PDF, upload page images instead.`);
  const truncated = text.length > MAX_CHARS;
  return { text: truncated ? text.slice(0, MAX_CHARS) : text, truncated };
}
